/// Fuentes de píxeles para los carteles de la ciudad.
///
/// Solo carteles: el contenido que hay que leer va en las tipografías del
/// sitio. Un párrafo en letra de 5×7 no se lee.
enum PixelFont {
  /// 5×7, para carteles grandes.
  big(5, 7),

  /// 3×5, para rótulos chicos (números de puerta, stickers).
  small(3, 5);

  const PixelFont(this.width, this.height);

  final int width;
  final int height;

  /// Si la fuente sabe dibujar [ch] (directo o sin tilde). Lo que no, sale
  /// como `?`: conviene filtrarlo antes de escribir texto que viene de datos.
  bool has(String ch) {
    final table = this == PixelFont.big ? _big : _small;
    final up = ch.toUpperCase();
    return table.containsKey(up) || table.containsKey(_fold(up));
  }

  List<String> glyph(String ch) {
    final table = this == PixelFont.big ? _big : _small;
    return table[ch] ?? table[_fold(ch)] ?? table['?']!;
  }

  int measure(String t) {
    var w = 0;
    for (final ch in t.toUpperCase().split('')) {
      final g = glyph(ch);
      w += (g.isEmpty ? width : g.first.length) + 1;
    }
    return w == 0 ? 0 : w - 1;
  }

  static String _fold(String ch) => switch (ch) {
        'Á' || 'À' => 'A',
        'É' => 'E',
        'Í' => 'I',
        'Ó' => 'O',
        'Ú' || 'Ü' => 'U',
        'Ñ' => 'N',
        _ => ch,
      };
}

